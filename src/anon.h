/* anon.h — анонимизация своей камеры: скрытие глаз в реальном времени. Только «Astra DS Video» (-DASTRA_VIDEO).
 * ДОГОВОР с разработчиком камеры (cam*.c) и дизайнером (ui.c).
 *
 * Модуль получает кадр I420 (плоскости Y, U, V) ПЕРЕД кодированием и обрабатывает его на месте:
 *   - лицо найдено уверенно -> ANON_SEND: глаза закрыты прямоугольником «средний цвет + шум + случайные
 *     ASCII-символы» (необратимо: в закрытой области не остаётся исходных пикселей);
 *   - лицо не найдено / мала уверенность / первые кадры после включения / потеря трекинга / резкое движение /
 *     смена освещения / лиц больше, чем умеем вести -> ANON_LOGO: буфер ЦЕЛИКОМ перезаписан сгенерированным
 *     кадром без единого пикселя камеры (логотип Astra DS — кошка «/\_/\ (=.=) >^<» крупно на тёмном фоне).
 *     Это и кодируется/уходит собеседникам. Возврат к ANON_SEND — только после нескольких уверенных кадров подряд;
 *   - ANON_DROP (0) — ошибка (неверные размеры/шаги, NULL) или обработка не уложилась во время: кадр НЕ
 *     кодировать и НЕ показывать. Содержимое буфера при этом не определено (может быть частично обработано).
 *
 * Как пользоваться из cam*.c (конвейер своей камеры):
 *   1. При открытии камеры (или смене размера кадра): ctx = anon_new(w, h); при закрытии — anon_free(ctx).
 *      anon_new вернёт NULL только при нехватке памяти или нелепом размере — тогда кадры НЕ отправлять.
 *   2. Для КАЖДОГО кадра, до кодирования и до предпросмотра: r = anon_frame(ctx, y, u, v, ys, cs, w, h).
 *        r == ANON_SEND, ANON_LOGO — кодировать этот буфер; r == ANON_DROP — выбросить кадр.
 *      Анонимизация выключена — anon_frame вернёт ANON_SEND, буфер не тронут.
 *   3. Предпросмотр у себя показывает ровно то, что уходит в эфир, КРОМЕ случая ANON_LOGO: тогда после
 *      кодирования (буфер логотипа уже не нужен) или на копии вызвать anon_preview_warning(ctx, ...) — модуль
 *      нарисует в буфер предупреждение для самого пользователя в стиле логотипа: зачёркнутое лицо из символов и
 *      надпись «ЛИЦО НЕ НАЙДЕНО» (через ui_tr, для английского интерфейса — «FACE NOT FOUND»).
 *      Это предупреждение тоже без единого пикселя камеры; собеседникам его не слать.
 *   4. Включение/выключение — anon_enable(ctx, on) или глобально anon_set_default(on): действует с первого же
 *      следующего кадра. Включение сбрасывает трекинг (первые кадры — ANON_LOGO).
 *
 * Как пользоваться из ui.c: флажок «Скрывать глаза» — anon_default()/anon_set_default(on) (сразу на все открытые
 * контексты); индикатор — anon_status(): ANON_OFF / ANON_TRACKING (глаза закрыты по найденному лицу) /
 * ANON_NOFACE (лицо не найдено, собеседники видят логотип).
 *
 * Потоки: anon_new/anon_free/anon_enable/anon_frame/anon_preview_warning — из одного потока на контекст (потока
 * камеры); anon_set_default/anon_default/anon_status — из любого потока. Ничего не пишется на диск и в журнал.
 * Память: < 200 КБ на контекст (не зависит от размера кадра, кроме мелких таблиц). */
#ifndef ANON_H
#define ANON_H
#ifdef ASTRA_VIDEO
#include <stdbool.h>
#include <stdint.h>

typedef struct AnonCtx AnonCtx;

/* Контекст под кадр w x h (чётные, 32..4096). NULL — нет памяти или неверный размер. */
AnonCtx *anon_new(int w, int h);
void anon_free(AnonCtx *c);
/* Включить/выключить на этом контексте (мгновенно, с ближайшего кадра). */
void anon_enable(AnonCtx *c, bool on);
bool anon_enabled(const AnonCtx *c);

/* Итог обработки кадра. */
enum { ANON_DROP = 0, ANON_SEND = 1, ANON_LOGO = 2 };
/* Обработать кадр на месте. ys — шаг строки Y, cs — шаг строки U и V (байты), w x h — как в anon_new. */
int anon_frame(AnonCtx *c, uint8_t *y, uint8_t *u, uint8_t *v, int ys, int cs, int w, int h);
/* То же, но с готовой уменьшенной Y (если конвертер кадра уже её считает — чтобы не уменьшать дважды):
 * sy — среднее блоков f x f плоскости Y (sw x sh, шаг строки sys >= sw), размеры — anon_small_size().
 * sy == NULL — модуль уменьшает сам (как anon_frame). */
int anon_frame_small(AnonCtx *c, uint8_t *y, uint8_t *u, uint8_t *v, int ys, int cs, int w, int h, const uint8_t *sy, int sys);
bool anon_small_size(const AnonCtx *c, int *sw, int *sh, int *f);   /* sw = w / f, sh = h / f, f = ceil(w / 320) */
/* Предупреждение для своего предпросмотра (только после ANON_LOGO): буфер целиком перезаписывается.
 * false — неверные аргументы (тогда предпросмотр не показывать). */
bool anon_preview_warning(AnonCtx *c, uint8_t *y, uint8_t *u, uint8_t *v, int ys, int cs, int w, int h);

/* Состояние для интерфейса. */
enum { ANON_OFF, ANON_TRACKING, ANON_NOFACE };
int anon_state(const AnonCtx *c);              /* после последнего кадра этого контекста */
int anon_status(void);                         /* то же для последнего обработанного кадра любого контекста */
int anon_faces(const AnonCtx *c);              /* сколько лиц закрыто в последнем кадре */

/* Глобальный флаг «Скрывать глаза»; начальное значение — ANON_DEFAULT_ON (решает владелец). */
#ifndef ANON_DEFAULT_ON
#define ANON_DEFAULT_ON 1
#endif
void anon_set_default(bool on);                /* меняет и всем открытым контекстам — с ближайшего кадра */
bool anon_default(void);

/* ---------- внутреннее (selftest, стенд) ---------- */
int anon_selftest(void (*check)(bool ok, const char *what));
/* --anontest=КАТАЛОГ: стенд точности на наборе изображений с разметкой глаз (только числа в консоль). */
int anon_test(const char *dir);
#endif
#endif
