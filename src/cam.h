/* cam.h — веб-камера в звонке, только «Astra DS Video» (-DASTRA_VIDEO). ДОГОВОР с дизайнером (ui.c).
 *
 * Камера идёт по ОСНОВНОМУ голосовому соединению (как «Включить камеру» в официальном клиенте, не Go Live):
 * op 12 со своим video_ssrc, self_video:true на основном шлюзе. Видео уходит только под сквозным шифрованием
 * DAVE: пока ключей группы нет (вы одни в канале или E2EE ещё согласуется) — фаза CAM_WAIT_E2EE, кадры не
 * отправляются (предпросмотр при этом работает).
 *
 * Все функции — из главного потока (потока интерфейса), если не сказано иное. Ничего не пишется на диск и в журнал.
 *
 * Как пользоваться из ui.c:
 *   1. Кнопка «[]/» в голосовой панели: cam_active() ? cam_stop() : cam_start(err, n) (ошибку показать ui_notice).
 *      Кнопка имеет смысл, только пока идёт звонок (voice_status: phase != VS_IDLE); вне звонка cam_start вернёт
 *      false с понятным текстом.
 *   2. Выбор устройства (настройки «Голос и видео» или правый щелчок по кнопке): cam_list() -> список имён,
 *      cam_select(id). Выбор действует со следующего cam_start (включённая камера переключается сама).
 *      Качество: cam_quality_name(0..CAM_Q_N-1), cam_quality_set(q).
 *   2а. Крупный вид одной камеры в панели видео — cam_want(user, CAM_FULL) + g_video_area (см. ниже).
 *   3. Плитки: в КАЖДОМ render() для каждой видимой плитки — g_cam_area(user, x, y, w, h) в клетках сетки
 *      (как g_video_area у зрителя трансляции). user == S.me_id — предпросмотр своей камеры. Плитку, для которой
 *      в кадре вывода (до ESC[?2026l) g_cam_area не позвали, клиент считает невидимой: её видео не собирается и
 *      не декодируется, память — до нуля. Отдельного cam_want() нет: видимость = вызов g_cam_area.
 *      Растр рисует само окно поверх клеток (вписанная картинка, поля чёрные); ui.c под плиткой рисует заглушку
 *      (аватар/имя) — она видна, пока кадра нет (cam_tile().shown == 0) и в --tui/--cli (g_video_supported() false).
 *   4. Кто с камерой: VoiceState.video (store.c, self_video из VOICE_STATE_UPDATE/READY) — для значка у участника
 *      в списке канала; cam_users() — участники ТЕКУЩЕГО звонка, чьё видео сервер объявил (op 12), то есть те,
 *      для кого есть смысл рисовать плитку.
 *   5. Индикатор: cam_state() — фаза, размер, к/с, ошибка; cam_tile() — состояние плитки участника.
 * Строки ошибок уже переведены (ui_tr внутри). */
#ifndef CAM_H
#define CAM_H
#ifdef ASTRA_VIDEO
#include <stdbool.h>
#include <stddef.h>
#include "mc.h"

/* ---------- устройства ---------- */
typedef struct {
    char id[256];                               /* Windows — символическая ссылка устройства, Linux — /dev/videoN */
    char name[96];                              /* имя для списка (UTF-8, уже очищено) */
} CamDevice;
int cam_list(CamDevice *out, int max);          /* перечень камер (саму камеру не включает); 0 — камер нет */
void cam_select(const char *id);                /* NULL или "" — первая в списке (по умолчанию) */
const char *cam_selected(void);                 /* "" — по умолчанию */

/* ---------- качество своей камеры (поле «КАЧЕСТВО» в диалоге) ---------- */
enum { CAM_Q_AUTO, CAM_Q_720, CAM_Q_480, CAM_Q_360, CAM_Q_N };   /* наибольший кадр в эфире: авто = 640x360 (как 360p) */
const char *cam_quality_name(int q);            /* подпись для списка (переведена): "Авто (до 720p)", "720p", ... */
void cam_quality_set(int q);                    /* действует со следующего включения (включённая — переключается сама) */
int cam_quality(void);                          /* CAM_Q_* */
void cam_mode_set(int q);                       /* то же, что cam_quality_set */

/* Анонимизация (скрытие глаз) — anon.h: флажок anon_set_default()/anon_default(); камера зовёт anon_frame для
 * каждого кадра до предпросмотра и до кодера (кадр, который anon_frame отверг, не показывается и не уходит). */

/* ---------- своя камера ---------- */
enum { CAM_OFF, CAM_STARTING, CAM_WAIT_E2EE, CAM_LIVE, CAM_FAILED };
typedef struct {
    int phase;                                  /* CAM_* */
    int w, h, fps;                              /* что отправляется (после выбора режима камеры) */
    int cam_w, cam_h;                           /* что даёт камера */
    char fmt[8];                                /* формат камеры: "NV12" / "YUY2" / "MJPG" */
    double fps_out, kbps;                       /* отправлено за последнюю секунду */
    long long frames, sent, dropped;            /* снято / отправлено кадров / выброшено (не в эфире, очередь) */
    char dev[96];                               /* имя открытой камеры */
    char err[128];                              /* CAM_FAILED: почему (камера занята, нет доступа, отключена...) */
} CamState;
/* Включить камеру в текущем звонке. false — сразу не вышло (err — по-человечески): нет звонка, нет камеры,
 * занята другой программой, нет доступа (Windows: «Параметры -> Конфиденциальность -> Камера»). Дальнейшие сбои
 * (отключили камеру, звонок оборвался) — фаза CAM_FAILED с текстом в cam_state().err; камера при этом уже закрыта. */
bool cam_start(char *err, size_t errn);
void cam_stop(void);                            /* выключить: камера закрывается сразу, кадры затираются */
bool cam_active(void);                          /* включена (STARTING/WAIT_E2EE/LIVE) */
void cam_state(CamState *out);

/* ---------- плитки (окно) ---------- */
#define CAM_TILES 8                             /* наибольшее число одновременно показываемых камер (с предпросмотром) */
/* Плитка видна в этом render(): прямоугольник в клетках сетки. user == S.me_id — предпросмотр своей камеры. */
void g_cam_area(u64 user, int x, int y, int w, int h);
typedef struct {
    bool video;                                 /* сервер объявил видео участника (для себя — камера включена) */
    bool shown;                                 /* в плитке уже есть кадр (иначе ui.c рисует заглушку) */
    bool e2ee;                                  /* кадры проходят через DAVE */
    bool unsupported;                           /* кодек не декодируется: «формат не поддерживается» */
    int w, h;                                   /* размер исходного кадра (0 — ещё не было) */
    long long frames, lost;                     /* собрано / выброшено кадров */
} CamTile;
bool cam_tile(u64 user, CamTile *out);          /* false — у участника нет видео */
/* Крупный просмотр одной камеры в панели видео (как зритель Go Live): cam_want(user, CAM_FULL) — кадры этого
 * участника (или свой предпросмотр, user == S.me_id) идут полным размером тем же путём, что трансляция: ui.c
 * заявляет область g_video_area() в каждом render(), окно рисует кадр (gvid_*). Пока выбран CAM_FULL, кадры
 * просматриваемой трансляции Go Live в панель не кладутся и не декодируются (звук трансляции идёт). Один участник
 * за раз; cam_want(другой, CAM_FULL) переключает, cam_want(user, CAM_OFF) или CAM_TILE — снимает крупный вид.
 * CAM_TILE — плитка (уменьшенный кадр; сама видимость плитки — по-прежнему вызов g_cam_area в render()).
 * Невидимые (ни плитки в этом кадре, ни крупного вида) — не собираются и не декодируются. */
enum { CAM_TILE = 1, CAM_FULL = 2 };            /* CAM_OFF (0) — не нужен */
void cam_want(u64 user, int mode);
int cam_users(u64 *out, int max);               /* участники звонка с видео (без себя) */
size_t cam_bytes(void);                         /* память камер сейчас: захват + кодер + приём + растр плиток, Б */

/* ---------- внутреннее (voice.c, gui_*, selftest) ---------- */
void cam_on_voice_end(void);                    /* звонок кончился: камера выключается, приём забывается */
void cam_request_idr(void);                     /* PLI зрителя: следующий кадр своей камеры — ключевой */
void cam_stop_nowait(void);                     /* паника: только флаг (процесс сейчас завершится) */
u64 cam_full_user(void);                        /* кто в крупном виде (0 — никто); из любого потока */
int cam_test(int secs, const char *id);         /* --camtest: короткая проверка камеры, только числа в консоль */
int cam_selftest(void (*check)(bool ok, const char *what));
#endif
#endif
